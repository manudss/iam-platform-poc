// Bundles chat.src.mjs (+ the `ai` chat classes) into ONE self-contained ES module: the plugin screen contract
// (a screen is one signed .mjs imported from a blob URL: no bare imports, no top-level await).
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../plugins/ai-assistant/screens/chat.mjs');
const r = await build({
  entryPoints: [join(here, 'chat.src.mjs')], bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022',
  minify: true, legalComments: 'none', define: { 'process.env.NODE_ENV': '"production"' }, logLevel: 'warning',
});
const banner = '// GENERATED by scripts/ai-assistant-ui/build.mjs from chat.src.mjs. Do not edit by hand. Bundles the AI SDK (`ai`, Apache-2.0) chat classes.\n';
const code = banner + r.outputFiles[0].text;
if (/^\s*import\s|from\s*["'](?!\.)[a-z@]/m.test(code.replace(/"[^"\n]*"/g, '""')) ) throw new Error('bundle still has imports');
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== code) { console.error('ai-assistant screen bundle is out of date: run `npm run build` in scripts/ai-assistant-ui'); process.exit(1); }
  console.log('ai-assistant screen bundle is up to date'); process.exit(0);
}
writeFileSync(out, code); console.log(`wrote ${out} (${code.length} bytes)`);
