#!/usr/bin/env node
/**
 * plugin-deps: plugin dependency autonomy (step 4).
 *
 * Rule: a plugin's folder carries ALL of its code AND the declaration of every dependency that code
 * imports. Each plugin has its own package.json; `createRequire` in plugin code anchors at it, so
 * resolution starts at the plugin folder and walks up: the plugin's own node_modules first, then the
 * repo-root node_modules, where the CONTROLLED shared install lives (this script generates the root
 * package.json as the exact union of what plugins declare - nothing else is installed there).
 *
 *   node scripts/plugin-deps.mjs            # rewrite the root package.json from the plugins' declarations
 *   node scripts/plugin-deps.mjs --check    # declarations, scan and root package.json must agree (CI)
 *
 * POC limit (documented in docs/plugins-dependencies.md): one shared install set at the repo root, no
 * per-plugin version isolation yet; the signature of a plugin covers its package.json, so a signed
 * plugin's dependency declaration cannot drift from its signed code unnoticed.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const PLUGINS = join(ROOT, 'plugins');
const check = process.argv.includes('--check');

/** Host-provided packages: the plugin DECLARES them but the API process supplies the one and only instance
 * (a second copy of the Nest framework would break `instanceof HttpException` across the plugin boundary).
 * The root install links them to the API's own copy instead of installing a duplicate. */
const HOST_PROVIDED = { '@nestjs/common': 'apps/api/node_modules/@nestjs/common' };

const BARE = [
  /\brequire\(\s*'([^']+)'/g,
  /\bcreateRequire\([\s\S]{0,200}?\)\s*\(\s*'([^']+)'/g, // inline: createRequire(<anchor>)('dep') - the anchor itself has parens
  /\bimport\s+(?:[\w${}*,\s]+\s+from\s+)?'([^']+)'/g,
  /\bimport\(\s*'([^']+)'/g,
];
const isBare = (s) => !s.startsWith('node:') && !s.startsWith('.') && !s.startsWith('/') && !s.startsWith('#');
const packageOf = (s) => (s.startsWith('@') ? s.split('/').slice(0, 2).join('/') : s.split('/')[0]);

function* mjsFiles(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name.startsWith('.')) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* mjsFiles(p);
    else if (e.name.endsWith('.mjs')) yield p;
  }
}

export function scanPlugin(dir) {
  const used = new Set();
  for (const f of mjsFiles(dir)) {
    const src = readFileSync(f, 'utf8');
    for (const re of BARE) for (const m of src.matchAll(re)) if (isBare(m[1])) used.add(packageOf(m[1]));
  }
  return [...used].sort();
}

const errors = [];
const union = {};
for (const id of readdirSync(PLUGINS)) {
  const dir = join(PLUGINS, id);
  const pkgPath = join(dir, 'package.json');
  if (!existsSync(join(dir, 'manifest.json'))) continue;
  if (!existsSync(pkgPath)) { errors.push(`${id}: no package.json (every plugin declares its dependencies, even zero)`); continue; }
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  const declared = Object.keys(pkg.dependencies ?? {}).sort();
  const used = scanPlugin(dir);
  for (const d of used) if (!declared.includes(d)) errors.push(`${id}: imports '${d}' but does not declare it in its package.json`);
  for (const d of declared) if (!used.includes(d)) errors.push(`${id}: declares '${d}' but no plugin code imports it`);
  for (const [d, range] of Object.entries(pkg.dependencies ?? {})) {
    if (union[d] && union[d] !== range) errors.push(`root: '${d}' declared as ${union[d]} and ${range} (POC: one shared version, align the plugins)`);
    union[d] = union[d] ?? range;
  }
}

const rootPkg = {
  name: 'iam-platform-plugins',
  private: true,
  version: '0.0.0',
  description: 'GENERATED by scripts/plugin-deps.mjs - the controlled shared install of every dependency the plugins declare (host-provided packages are linked to the API copy, not installed). Do not edit by hand.',
  dependencies: Object.fromEntries(Object.entries(union).filter(([d]) => !HOST_PROVIDED[d]).sort()),
};
const rootPath = join(ROOT, 'package.json');
const current = existsSync(rootPath) ? readFileSync(rootPath, 'utf8') : '';
if (current !== JSON.stringify(rootPkg, null, 2) + '\n') {
  if (check) errors.push('root package.json is not the generated union of the plugin declarations (run scripts/plugin-deps.mjs)');
  else { writeFileSync(rootPath, JSON.stringify(rootPkg, null, 2) + '\n'); console.log(`plugin-deps: wrote package.json (${Object.keys(union).length} shared dependencies)`); }
}
if (check) for (const d of Object.keys(union)) if (!existsSync(join(ROOT, 'node_modules', d))) errors.push(`root: '${d}' is declared but not installed (run npm install at the repo root, then scripts/plugin-deps.mjs)`);

// Host-provided packages: a relative symlink into the API's install, recreated by every default run (npm ci
// wipes node_modules, so the CI order is: npm ci, then this script, then --check).
import { symlinkSync, rmSync, lstatSync } from 'node:fs';
for (const [d, target] of Object.entries(HOST_PROVIDED)) {
  const link = join(ROOT, 'node_modules', d);
  if (check) {
    if (!existsSync(link)) errors.push(`root: host-provided '${d}' is not linked (run scripts/plugin-deps.mjs)`);
  } else {
    if (existsSync(link) && !lstatSync(link).isSymbolicLink()) rmSync(link, { recursive: true }); // replace a real duplicate
    if (!existsSync(link)) { mkdirSync(dirname(link), { recursive: true }); symlinkSync(`../../${target}`, link, 'dir'); console.log(`plugin-deps: linked host-provided ${d} -> ${target}`); }
  }
}

if (errors.length) { console.error('plugin-deps: FAILED'); for (const e of errors) console.error(`  - ${e}`); process.exit(1); }
console.log(`plugin-deps: ${check ? 'ok' : 'done'} (${Object.keys(union).length} shared dependencies)`);
