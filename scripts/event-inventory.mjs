#!/usr/bin/env node
/**
 * Event-circuit inventory (plan step 3, PR "inventaire et garde-fou").
 *
 * Scans the API (apps/api/src) and the Rust core (core/crates) for every place that emits or listens to an
 * application event, and for the direct cross-module calls that bypass the bus. The result is written to
 * docs/event-inventory.md. With --check the committed document is compared to a fresh scan and any difference
 * fails the run: a NEW circuit (an emitter, a listener, a direct call) cannot appear unnoticed.
 *
 * Usage: node scripts/event-inventory.mjs [--check]
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const DOC = join(ROOT, 'docs/event-inventory.md');

function* walk(dir, ext) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === 'dist' || name === 'target' || name.startsWith('.')) continue;
    const p = join(dir, name);
    const s = statSync(p);
    if (s.isDirectory()) yield* walk(p, ext);
    else if (ext.some((e) => name.endsWith(e))) yield p;
  }
}

// Each rule: id, where to look, pattern, how to label a match. Tests are inventory too: a circuit used only in
// tests is still a circuit, but it is listed apart so the production table stays readable.
const RULES = [
  { id: 'bus.emit (API -> core bus)', files: 'api', re: /(?:bus|host)\.(?:emit|call)\(\s*(?:tenant,?\s*)?'([a-z0-9._-]+)'/gi, kind: 'emitter' },
  { id: 'ApplicationBus.emit', files: 'api', re: /events\?*\.emit\(\{\s*type:\s*'([a-z0-9._-]+)'/gi, kind: 'emitter' },
  { id: 'ApplicationBus local emit helper', files: 'api', re: /this\.emit\('([a-z0-9._-]+)'/gi, kind: 'emitter' },
  { id: 'plugins.emit (async hook)', files: 'api', re: /plugins!?\.emit\(\s*\w+,\s*'([a-z0-9._-]+)'/gi, kind: 'emitter' },
  { id: 'registry.emit (async hook)', files: 'api', re: /\.emit\(\s*\w+,\s*'(notify\.send|identity\.changed|workflow\.step|connector\.[a-z]+|audit\.event)'/gi, kind: 'emitter' },
  { id: 'callSlot (blocking hook)', files: 'api', re: /callSlot(?:<[^>]*>)?\(\s*\w+,\s*'([a-z0-9._-]+)'/gi, kind: 'caller' },
  { id: 'registry.control/queryHook (blocking hook, step 3)', files: 'api', re: /\.(?:control|queryHook)(?:<[^>]*>)?\(\s*\w+,\s*'([a-z0-9._-]+)'/gi, kind: 'caller' },
  { id: 'ApplicationBus.on (in-process listener)', files: 'api', re: /events\.on\(/gi, kind: 'listener' },
  { id: 'NatsService (IAM_EVENTS circuit)', files: 'api', re: /NatsService/g, kind: 'circuit' },
  { id: 'core bus emit (Rust)', files: 'core', re: /\.(?:emit|notify|call|query)\(&e(?:nv)?\b/g, kind: 'emitter' },
  { id: 'core bus wiring event', files: 'core', re: /bus\.emit\(\s*"([a-z0-9._-]+)"/g, kind: 'emitter' },
  { id: 'oidc provider event hook', files: 'api', re: /provider\.on\(ev/g, kind: 'listener' },
];

// Architecture guard: the registry may invoke handlers only through the bus host, never through a local fallback.
const registrySource = readFileSync(join(ROOT, 'apps/api/src/plugins/v1/registry.ts'), 'utf8');
if (/handlers\[hook\]\s*\(/.test(registrySource) || registrySource.includes('if (this.bus?.routed')) throw new Error('local registry handler path is forbidden');
for (const file of walk(join(ROOT, 'apps/api/src'), ['.ts'])) {
  if (/\.spec\.ts$/.test(file)) continue;
  const text = readFileSync(file, 'utf8');
  if (/\bAppEvents\b|\bNatsService\b|\bActivationConsumer\b/.test(text)) throw new Error(`retired event circuit: ${relative(ROOT, file)}`);
}

function scan() {
  const rows = [];
  for (const rule of RULES) {
    const dirs = rule.files === 'api' ? [join(ROOT, 'apps/api/src')] : [join(ROOT, 'core/crates')];
    const exts = rule.files === 'api' ? ['.ts'] : ['.rs'];
    for (const dir of dirs) {
      for (const file of walk(dir, exts)) {
        const rel = relative(ROOT, file);
        const isTest = /\.(spec|e2e\.spec)\.ts$|tests\//.test(rel);
        const text = readFileSync(file, 'utf8');
        const lines = text.split('\n');
        lines.forEach((line, i) => {
          for (const m of line.matchAll(rule.re)) {
            rows.push({ rule: rule.id, kind: rule.kind, detail: m[1] ?? '', file: rel, line: i + 1, test: isTest });
          }
        });
      }
    }
  }
  rows.sort((a, b) => a.rule.localeCompare(b.rule) || a.file.localeCompare(b.file) || a.line - b.line);
  return rows;
}

function render(rows) {
  const prod = rows.filter((r) => !r.test);
  const tst = rows.filter((r) => r.test);
  const out = [];
  out.push('# Event circuit inventory');
  out.push('');
  out.push('GENERATED by `node scripts/event-inventory.mjs` - do not edit by hand. The CI guard');
  out.push('(`--check`) fails when a fresh scan differs from this file: a new emitter, listener or direct');
  out.push('circuit must be added here on purpose. Plan step 3: every circuit listed here either goes');
  out.push('through the core bus or is a documented exception (docs/event-bus.md).');
  out.push('');
  out.push(`Production code: ${prod.length} points. Test code: ${tst.length} points.`);
  out.push('');
  const table = (list) => {
    out.push('| Circuit | Role | Event / detail | Place |');
    out.push('|---|---|---|---|');
    for (const r of list) out.push(`| ${r.rule} | ${r.kind} | ${r.detail || '-'} | ${r.file}:${r.line} |`);
    out.push('');
  };
  out.push('## Production'); out.push(''); table(prod);
  out.push('## Tests'); out.push(''); table(tst);
  return out.join('\n');
}

const fresh = render(scan());
if (process.argv.includes('--check')) {
  let committed = '';
  try { committed = readFileSync(DOC, 'utf8'); } catch { /* missing */ }
  if (committed.trim() !== fresh.trim()) {
    console.error('event-inventory: docs/event-inventory.md is STALE (a circuit appeared, moved or disappeared).');
    console.error('Run `node scripts/event-inventory.mjs` and commit the result.');
    process.exit(1);
  }
  console.log('event-inventory: up to date');
} else {
  writeFileSync(DOC, fresh);
  console.log(`event-inventory: wrote ${relative(ROOT, DOC)}`);
}
